using System.Text.Json;
using Api2Skill.Model;

namespace Api2Skill.Emit;

/// <summary>
/// Python dispatcher (<c>python3 scripts/call.py --</c>). Standard library only.
/// OAuth tokens are read from <c>.auth-cache.json</c>; <c>api2skill login</c> obtains them.
/// When <c>scripts/requirements.txt</c> lists packages, the script installs them once into
/// <c>scripts/.pydeps</c>.
/// </summary>
public sealed class PyEmitter : IScriptEmitter
{
    public string Key => "py";

    public string FileExtension => "py";

    public string RunnerDescription => "python3 scripts/call.py --";

    public void Emit(SkillModel model, DirectoryInfo skillDirectory)
    {
        var scriptsDirectory = Directory.CreateDirectory(Path.Combine(skillDirectory.FullName, "scripts"));
        File.WriteAllText(Path.Combine(scriptsDirectory.FullName, "call.py"), Generate(model));
        File.WriteAllText(
            Path.Combine(scriptsDirectory.FullName, "requirements.txt"),
            """
            # Optional third-party packages for this skill.
            # call.py installs this file into scripts/.pydeps when any requirement is listed.
            # Lines that are blank or start with # are ignored.

            """);
    }

    private static string Generate(SkillModel model)
    {
        var operations = EmitterOperations.DistinctByOperationId(model)
            .Select(op => new
            {
                id = op.OperationId,
                method = op.Method.Method,
                path = op.PathTemplate,
                hasBody = op.RequestBody is not null,
                contentType = op.RequestBody?.ContentType,
                parameters = op.Parameters.Select(p => new { name = p.Name, location = LocationKey(p.In) }),
                securitySchemeIds = op.SecuritySchemeIds,
                authProfileNames = op.AuthProfileNames,
            });
        var schemes = model.SecuritySchemes.Select(scheme => new
        {
            id = scheme.Id,
            kind = SchemeKindKey(scheme.Kind),
            apiKeyName = scheme.ApiKeyName,
            apiKeyLocation = scheme.ApiKeyLocation switch
            {
                ApiKeyLocation.Query => "query",
                ApiKeyLocation.Header => "header",
                _ => (string?)null,
            },
        });

        var opsJson = JsonSerializer.Serialize(operations);
        var schemesJson = JsonSerializer.Serialize(schemes);
        var baseUrlJson = JsonSerializer.Serialize(model.BaseUrl ?? "");
        var insecure = model.InsecureDefault ? "1" : "0";

        return Template
            .Replace("__OPS_JSON__", opsJson, StringComparison.Ordinal)
            .Replace("__SCHEMES_JSON__", schemesJson, StringComparison.Ordinal)
            .Replace("__BASE_URL_JSON__", baseUrlJson, StringComparison.Ordinal)
            .Replace("__INSECURE__", insecure, StringComparison.Ordinal);
    }

    private static string LocationKey(ParameterLocation location) => location switch
    {
        ParameterLocation.Path => "path",
        ParameterLocation.Header => "header",
        _ => "query",
    };

    private static string SchemeKindKey(SecuritySchemeKind kind) => kind switch
    {
        SecuritySchemeKind.ApiKey => "apiKey",
        SecuritySchemeKind.Bearer => "bearer",
        SecuritySchemeKind.Basic => "basic",
        SecuritySchemeKind.OAuth2 => "oauth2",
        _ => "unsupported",
    };

    private const string Template = """
        #!/usr/bin/env python3
        # Generated by api2skill — do not edit by hand; re-run the generator instead.
        # Usage: python3 call.py <operationId> [--<param> <value> ...] [--body <json|@file>]
        import base64
        import hashlib
        import json
        import os
        import ssl
        import subprocess
        import sys
        import urllib.error
        import urllib.parse
        import urllib.request
        from datetime import datetime, timedelta, timezone
        from pathlib import Path

        SCRIPT_DIR = Path(__file__).resolve().parent
        SKILL_ROOT = SCRIPT_DIR.parent
        BASE_URL_DEFAULT = __BASE_URL_JSON__
        INSECURE_DEFAULT = "__INSECURE__"
        OPERATIONS = {op["id"]: op for op in json.loads(r'''
        __OPS_JSON__
        ''')}
        SCHEMES = {scheme["id"]: scheme for scheme in json.loads(r'''
        __SCHEMES_JSON__
        ''')}


        class AuthError(Exception):
            pass


        def ensure_deps():
            req = SCRIPT_DIR / "requirements.txt"
            if not req.is_file():
                return
            listed = [
                line.strip()
                for line in req.read_text(encoding="utf-8").splitlines()
                if line.strip() and not line.strip().startswith("#")
            ]
            vendor = SCRIPT_DIR / ".pydeps"
            if str(vendor) not in sys.path:
                sys.path.insert(0, str(vendor))
            if not listed:
                return
            digest = hashlib.sha256(req.read_bytes()).hexdigest()
            stamp = vendor / ".stamp"
            if stamp.is_file() and stamp.read_text(encoding="utf-8").strip() == digest:
                return
            vendor.mkdir(parents=True, exist_ok=True)
            subprocess.check_call(
                [sys.executable, "-m", "pip", "install", "-r", str(req), "--target", str(vendor)]
            )
            stamp.write_text(digest + "\n", encoding="utf-8")


        def load_json(path, warn_name):
            if not path.is_file():
                return None
            try:
                return json.loads(path.read_text(encoding="utf-8"))
            except json.JSONDecodeError as ex:
                print(
                    f"warning: {warn_name} is not valid JSON ({ex}); proceeding as if it were absent.",
                    file=sys.stderr,
                )
                return None


        def parse_args(rest):
            values = {}
            body = None
            i = 0
            while i < len(rest):
                token = rest[i]
                if not token.startswith("--") or i + 1 >= len(rest):
                    i += 1
                    continue
                key = token[2:]
                value = rest[i + 1]
                i += 2
                if key == "body":
                    body = value
                else:
                    values[key] = value
            return values, body


        def resolve_secret(raw, secrets):
            if not isinstance(raw, str):
                raise AuthError("auth.json value is missing.")
            if raw.startswith("{secret:") and raw.endswith("}"):
                key = raw[len("{secret:") : -1]
                if not isinstance(secrets, dict) or key not in secrets or secrets[key] is None:
                    raise AuthError(f'secrets.json has no value for "{key}" (referenced by auth.json).')
                return str(secrets[key])
            return raw


        def find_profile(auth, name):
            if not isinstance(auth, dict):
                return None
            for profile in auth.get("profiles") or []:
                if isinstance(profile, dict) and profile.get("name") == name:
                    return profile
            return None


        def scheme_secret(secrets, scheme_id, key):
            if not isinstance(secrets, dict):
                return None
            block = secrets.get(scheme_id)
            if not isinstance(block, dict):
                return None
            value = block.get(key)
            return None if value is None else str(value)


        def parse_expires(value):
            text = value.strip().replace("Z", "+00:00")
            if "." in text:
                date, rest = text.split(".", 1)
                sign = "+" if "+" in rest else "-" if "-" in rest[1:] else ""
                if sign:
                    frac, offset = rest.split(sign, 1)
                    text = f"{date}.{(frac + '000000')[:6]}{sign}{offset}"
            parsed = datetime.fromisoformat(text)
            if parsed.tzinfo is None:
                parsed = parsed.replace(tzinfo=timezone.utc)
            return parsed


        def cached_access_token(profile_name):
            path = SKILL_ROOT / ".auth-cache.json"
            cache = load_json(path, ".auth-cache.json") or {}
            entry = cache.get(profile_name) if isinstance(cache, dict) else None
            token = entry.get("access_token") if isinstance(entry, dict) else None
            if not token:
                raise AuthError(
                    f"No usable token for auth profile '{profile_name}'. "
                    f"Run: api2skill login --skill {SKILL_ROOT} --profile {profile_name}"
                )
            expires_at = entry.get("expires_at")
            if isinstance(expires_at, str) and expires_at:
                try:
                    if parse_expires(expires_at) <= datetime.now(timezone.utc) + timedelta(seconds=60):
                        raise AuthError(
                            f"No usable token for auth profile '{profile_name}'. "
                            f"Run: api2skill login --skill {SKILL_ROOT} --profile {profile_name}"
                        )
                except AuthError:
                    raise
                except ValueError:
                    pass
            return str(token)


        def apply_profile(profile, profile_name, secrets, query, headers):
            kind = profile.get("type")
            if kind == "bearer":
                token = resolve_secret(profile.get("token"), secrets)
                value = token if token.lower().startswith("bearer ") else f"Bearer {token}"
                headers.append(("Authorization", value))
            elif kind == "basic":
                user = resolve_secret(profile.get("username"), secrets)
                password = resolve_secret(profile.get("password"), secrets)
                encoded = base64.b64encode(f"{user}:{password}".encode("utf-8")).decode("ascii")
                headers.append(("Authorization", f"Basic {encoded}"))
            elif kind == "custom":
                for header in profile.get("headers") or []:
                    if not isinstance(header, dict):
                        continue
                    name = header.get("name") or ""
                    headers.append((str(name), resolve_secret(header.get("value"), secrets)))
            elif kind == "script":
                command = profile.get("command") or ""
                header_name = profile.get("header") or "Authorization"
                completed = subprocess.run(
                    command,
                    shell=True,
                    cwd=str(SKILL_ROOT),
                    capture_output=True,
                    text=True,
                )
                if completed.returncode != 0:
                    raise AuthError(
                        f"Script command for auth profile '{profile_name}' exited with code {completed.returncode}: {completed.stderr.strip()}"
                    )
                token = completed.stdout.strip()
                if profile.get("bearerPrefix") is True and not token.lower().startswith("bearer "):
                    token = f"Bearer {token}"
                headers.append((str(header_name), token))
            elif kind == "oauth2":
                headers.append(("Authorization", f"Bearer {cached_access_token(profile_name)}"))
            else:
                raise AuthError(f"Auth profile type '{kind}' is not supported by this generated dispatcher yet.")


        def apply_scheme(scheme, secrets, query, headers):
            kind = scheme.get("kind")
            scheme_id = scheme.get("id")
            if kind == "apiKey":
                key = scheme_secret(secrets, scheme_id, "apiKey")
                if key is None:
                    print(
                        f"warning: no apiKey configured for scheme '{scheme_id}' in secrets.json — sending unauthenticated.",
                        file=sys.stderr,
                    )
                    return
                name = scheme.get("apiKeyName") or ""
                if scheme.get("apiKeyLocation") == "query":
                    query.append(f"{urllib.parse.quote(str(name), safe='')}={urllib.parse.quote(key, safe='')}")
                else:
                    headers.append((str(name), key))
            elif kind == "bearer":
                token = scheme_secret(secrets, scheme_id, "bearerToken")
                if token is None:
                    print(
                        f"warning: no bearerToken configured for scheme '{scheme_id}' in secrets.json — sending unauthenticated.",
                        file=sys.stderr,
                    )
                    return
                headers.append(("Authorization", f"Bearer {token}"))
            elif kind == "basic":
                user = scheme_secret(secrets, scheme_id, "username")
                password = scheme_secret(secrets, scheme_id, "password")
                if user is None or password is None:
                    print(
                        f"warning: no username/password configured for scheme '{scheme_id}' in secrets.json — sending unauthenticated.",
                        file=sys.stderr,
                    )
                    return
                encoded = base64.b64encode(f"{user}:{password}".encode("utf-8")).decode("ascii")
                headers.append(("Authorization", f"Basic {encoded}"))
            elif kind == "oauth2":
                print(
                    f"warning: scheme '{scheme_id}' is oauth2. Obtain a token with `api2skill login` and an auth.json profile. Sending unauthenticated.",
                    file=sys.stderr,
                )
            else:
                print(
                    f"warning: scheme '{scheme_id}' ({kind}) is not a supported auth kind — sending unauthenticated.",
                    file=sys.stderr,
                )


        def main(argv):
            ensure_deps()
            if not argv or argv[0] in ("-h", "--help"):
                names = ", ".join(sorted(OPERATIONS))
                print(
                    "Usage: python3 call.py <operationId> [--<param> <value> ...] [--body <json|@file>]",
                    file=sys.stderr,
                )
                print(f"Known operations: {names}", file=sys.stderr)
                return 2
            operation_id = argv[0]
            op = OPERATIONS.get(operation_id)
            if op is None:
                names = ", ".join(sorted(OPERATIONS))
                print(f"Unknown operationId '{operation_id}'.", file=sys.stderr)
                print(f"Known operations: {names}", file=sys.stderr)
                return 2

            param_values, body = parse_args(argv[1:])
            secrets = load_json(SKILL_ROOT / "secrets.json", "secrets.json")
            configured = ""
            if isinstance(secrets, dict) and isinstance(secrets.get("baseUrl"), str):
                configured = secrets["baseUrl"]
            if not configured:
                configured = BASE_URL_DEFAULT
            base_url = os.environ.get("API2SKILL_BASE_URL") or configured
            if not str(base_url).strip():
                print(
                    'No base URL configured. Set API2SKILL_BASE_URL or add "baseUrl" to secrets.json.',
                    file=sys.stderr,
                )
                return 2

            path = op["path"]
            query = []
            headers = []
            for param in op["parameters"]:
                value = param_values.get(param["name"])
                if value is None:
                    continue
                location = param["location"]
                if location == "path":
                    path = path.replace("{" + param["name"] + "}", urllib.parse.quote(value, safe=""))
                elif location == "query":
                    query.append(
                        f"{urllib.parse.quote(param['name'], safe='')}={urllib.parse.quote(value, safe='')}"
                    )
                elif location == "header":
                    headers.append((param["name"], value))

            try:
                profiles = op.get("authProfileNames") or []
                if profiles:
                    auth = load_json(SKILL_ROOT / "auth.json", "auth.json")
                    for profile_name in profiles:
                        profile = find_profile(auth, profile_name)
                        if profile is None:
                            raise AuthError(
                                f"auth.json has no profile named '{profile_name}' (referenced by operation '{operation_id}')."
                            )
                        apply_profile(profile, profile_name, secrets, query, headers)
                else:
                    for scheme_id in op.get("securitySchemeIds") or []:
                        scheme = SCHEMES.get(scheme_id)
                        if scheme is not None:
                            apply_scheme(scheme, secrets, query, headers)
            except AuthError as ex:
                print(str(ex), file=sys.stderr)
                return 2

            url = str(base_url).rstrip("/") + path
            if query:
                url += "?" + "&".join(query)
            data = None
            if op.get("hasBody"):
                body_text = body if body is not None else "{}"
                if body_text.startswith("@"):
                    body_text = Path(body_text[1:]).read_text(encoding="utf-8")
                data = body_text.encode("utf-8")
                headers.append(("Content-Type", op.get("contentType") or "application/json"))

            for name, value in headers:
                if "\r" in value or "\n" in value:
                    print(f"Invalid value for header '{name}': control characters are not allowed.", file=sys.stderr)
                    return 2

            request = urllib.request.Request(url, data=data, method=op["method"])
            for name, value in headers:
                request.add_header(name, value)

            insecure = (os.environ.get("API2SKILL_INSECURE") or INSECURE_DEFAULT) == "1"
            context = ssl._create_unverified_context() if insecure else ssl.create_default_context()
            try:
                with urllib.request.urlopen(request, context=context) as response:
                    text = response.read().decode("utf-8", errors="replace")
                    print(text)
                    return 0
            except urllib.error.HTTPError as ex:
                text = ex.read().decode("utf-8", errors="replace")
                print(text)
                print(f"HTTP {ex.code} {ex.reason}", file=sys.stderr)
                return 1
            except urllib.error.URLError as ex:
                print(f"Network error calling {base_url}: {ex.reason}", file=sys.stderr)
                return 3


        if __name__ == "__main__":
            try:
                raise SystemExit(main(sys.argv[1:]))
            except BrokenPipeError:
                raise SystemExit(0)
        """;
}
